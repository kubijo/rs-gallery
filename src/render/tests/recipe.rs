/// Write `text` to a recipe in its own scratch directory,
/// and read it back. Its own, because a recipe's `out`
/// resolves against the file, so the directory is part
/// of what's under test.
fn recipe(name: &str, text: &str, out: Option<&str>) -> Result<Capture, Diagnostic> {
    recipe_with(name, text, out, &RecordDefaults::default())
}

/// [`recipe`], read in a catalog whose `[record]` sets `defaults`.
fn recipe_with(
    name: &str,
    text: &str,
    out: Option<&str>,
    defaults: &RecordDefaults,
) -> Result<Capture, Diagnostic> {
    let dir = Utf8PathBuf::from_path_buf(std::env::temp_dir())
        .expect("a UTF-8 temp dir")
        .join(format!("gallery-recipe-{name}"));
    std::fs::create_dir_all(&dir).expect("scratch dir");
    let path = dir.join("capture.toml");
    std::fs::write(&path, text).expect("write recipe");
    let catalog = Defaults {
        record: *defaults,
        ..Defaults::default()
    };
    read_recipe(&path, out.map(Utf8Path::new), &catalog)
}

/// [`recipe_with`] of one shot, `a` of scene `s`
/// into `r` at 10×10, `shot` the rest of its table.
fn one_shot(
    name: &str,
    shot: toml::Table,
    defaults: &RecordDefaults,
) -> Result<Capture, Diagnostic> {
    let mut table = toml::toml! {
        name = "a"
        scene = "s"
    };
    table.extend(shot);
    let mut recipe = toml::toml! {
        out = "r"
        size = "10x10"
    };
    recipe.insert("shot".to_owned(), vec![toml::Value::from(table)].into());
    let text = toml::to_string(&recipe).expect("BUG: a table writes as TOML");
    recipe_with(name, &text, None, defaults)
}

#[test]
fn a_catalogs_hold_pauses_a_plays_recording_and_leaves_one_without_a_play_be() {
    let catalog = RecordDefaults {
        hold: Some(0.25),
        ..RecordDefaults::default()
    };
    let read = |name: &str, shot| {
        one_shot(name, shot, &catalog)
            .unwrap_or_else(|e| panic!("{name}: {}", e.summary()))
            .shots[0]
            .record
            .expect("a recording")
    };
    let timed = read(
        "catalog-hold-timed",
        toml::toml! { record = { fps = 30, seconds = 1 } },
    );
    assert_eq!(timed.hold, None, "no steps to pause at");
    let played = read(
        "catalog-hold-played",
        toml::toml! {
            play = "p"
            record = { fps = 30 }
        },
    );
    assert_eq!(played.hold, Some(0.25));
    let own = read(
        "catalog-hold-own",
        toml::toml! {
            play = "p"
            record = { fps = 30, hold = 0 }
        },
    );
    assert_eq!(own.hold, Some(0.0), "the shot's own outranks the catalog's");
}

