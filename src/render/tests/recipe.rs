#[test]
fn a_generated_recipe_reads_back_as_the_state_it_was_generated_from() {
    // The point of generating one: its values are already the spelling the parser takes,
    // so the first edit is the only thing that changes what renders.
    let scene = crate::test_support::scene("knobs", "demo", true);
    let declared = vec![
        KnobState::Text {
            label: "caption, long".to_owned(),
            value: "hi there".to_owned(),
        },
        KnobState::Toggle {
            label: "night".to_owned(),
            value: true,
        },
        KnobState::Slider {
            label: "width (chars)".to_owned(),
            value: 1.5,
            min: 0.0,
            max: 2.0,
            step: 0.1,
        },
        KnobState::Color {
            label: "tint".to_owned(),
            value: egui::Color32::from_rgb(0xE8, 0xA3, 0x3D),
        },
        select("body", &["sedan", "suv"]),
        KnobState::Pad2D {
            label: "offset".to_owned(),
            x: 0.25,
            y: -0.5,
            min_x: -1.0,
            max_x: 1.0,
            min_y: -1.0,
            max_y: 1.0,
            invert_y: false,
        },
    ];
    let generated = capture_template(&scene, &declared, egui::vec2(320.0, 200.0), 2.0);

    let dir = Utf8PathBuf::from_path_buf(std::env::temp_dir())
        .expect("a UTF-8 temp dir")
        .join("gallery-recipe-round-trip");
    std::fs::create_dir_all(&dir).expect("scratch dir");
    let path = dir.join("capture.toml");
    std::fs::write(&path, &generated).expect("write recipe");
    let shots = read_recipe(&path, None)
        .expect("the generated recipe parses")
        .shots;

    // Applied to knobs sitting at other values,
    // every one comes back to where it started.
    let mut store = declared.clone();
    for knob in &mut store {
        match knob {
            KnobState::Button { clicked, .. } => *clicked = false,
            KnobState::Text { value, .. } => value.clear(),
            KnobState::Toggle { value, .. } => *value = false,
            KnobState::Slider { value, .. } => *value = 0.0,
            KnobState::Color { value, .. } => *value = egui::Color32::BLACK,
            KnobState::Select { value, .. } | KnobState::IconButtons { value, .. } => *value = 0,
            KnobState::Pad2D { x, y, .. } => (*x, *y) = (0.0, 0.0),
            KnobState::Group { .. } => {}
        }
    }
    assert_eq!(
        shots[0].scale, 2.0,
        "a run that magnified generates a recipe that magnifies, or it renders \
             something other than what it was generated from"
    );
    let mut ledger = Ledger::new(shots[0].knobs.clone());
    ledger
        .apply_knobs(&mut store)
        .expect("every generated key names its knob");
    assert_eq!(ledger.unlanded().count(), 0, "no key went unmatched");
    for (before, after) in declared.iter().zip(&store) {
        assert_eq!(
            control_value(before),
            control_value(after),
            "knob {:?} round-tripped",
            before.label()
        );
    }
}

#[test]
fn recipe_globals_inherit_from_the_root_and_a_shot_wins() {
    let dir = Utf8PathBuf::from_path_buf(std::env::temp_dir())
        .expect("a UTF-8 temp dir")
        .join("gallery-global-recipe");
    std::fs::create_dir_all(&dir).expect("scratch dir");
    let path = dir.join("capture.toml");
    std::fs::write(
        &path,
        indoc! {r#"
                out = "renders"
                size = "320x200"

                [globals]
                Theme = "not an option"
                Language = "English"

                [[shot]]
                name = "dark-finnish"
                scene = "settings"

                [shot.globals]
                Theme = "Dark"
                Language = "Finnish"
            "#},
    )
    .expect("write recipe");

    let shot = read_recipe(&path, None)
        .expect("global recipe parses")
        .shots
        .into_iter()
        .next()
        .expect("one shot");
    let mut declared = vec![
        select("Theme", &["System", "Light", "Dark"]),
        select("Language", &["English", "Finnish"]),
    ];
    let mut ledger = Ledger::new(shot.globals.clone());
    ledger
        .apply_knobs(&mut declared)
        .expect("all globals apply");

    assert_eq!(shot.globals.len(), 2, "shot keys replace inherited keys");
    assert_eq!(ledger.unlanded().count(), 0);
    assert!(matches!(declared[0], KnobState::Select { value: 2, .. }));
    assert!(matches!(declared[1], KnobState::Select { value: 1, .. }));
}

#[test]
fn a_generated_recipe_writes_globals_before_the_shot() {
    let scene = crate::test_support::scene("settings", "demo", true);
    let globals = vec![
        select("Theme", &["System", "Light", "Dark"]),
        select("Language", &["English", "Finnish"]),
    ];
    let generated = capture_template_with_globals(
        &scene,
        &globals,
        &[],
        egui::vec2(320.0, 200.0),
        DEFAULT_SCALE,
    );

    let globals_at = generated.find("[globals]").expect("a globals table");
    let shot_at = generated.find("[[shot]]").expect("a shot");
    assert!(globals_at < shot_at, "root defaults precede the shot");
    assert!(generated.contains("Theme = \"System\""));
    assert!(generated.contains("Language = \"English\""));
}

