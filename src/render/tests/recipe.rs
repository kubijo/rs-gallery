#[test]
fn generated_recipes_round_trip_escaped_labels_and_values() {
    let scene = crate::test_support::scene("escaped", "capture", true);
    for value in [
        "a=b",
        "'\"\\",
        "line\nreturn\rtab\t",
        "\0\u{7}\u{b}\u{1b}\u{7f}",
        "ää 😀",
    ] {
        let label = format!("label {value}");
        let controls = vec![
            KnobState::Group {
                label: "group\nstill a heading\u{7}".to_owned(),
            },
            KnobState::Text {
                label: label.clone(),
                value: value.to_owned(),
            },
            select("choice", &[value]),
        ];
        let generated = capture_template_with_globals(
            &scene,
            &controls,
            &controls,
            DEFAULT_SIZE,
            DEFAULT_SCALE,
        );
        let recipe: Recipe = toml::from_str(&generated).expect("generated recipe is valid TOML");
        assert_eq!(recipe.globals[&label].as_str(), Some(value));
        assert_eq!(recipe.shots[0].knobs[&label].as_str(), Some(value));
        assert_eq!(recipe.shots[0].knobs["choice"].as_str(), Some(value));
    }
}

